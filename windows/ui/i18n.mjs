let language = 'zh-Hant';
export function resolveLanguage(value, preferred = globalThis.navigator?.language || 'zh-Hant') {
  if (value && value !== 'auto') return languages.some(([code]) => code === value) ? value : 'zh-Hant';
  if (/^zh-(CN|SG|Hans)/i.test(preferred)) return 'zh-Hans';
  if (/^zh/i.test(preferred)) return 'zh-Hant';
  if (/^ja/i.test(preferred)) return 'ja';
  if (/^ko/i.test(preferred)) return 'ko';
  return 'en';
}
export function setLanguage(value) { language = resolveLanguage(value); return language; }
export function getLanguage() { return language; }
export function t(key) {
  const index = { 'zh-Hant': 0, en: 1, ja: 2, ko: 3, 'zh-Hans': 4 }[language] ?? 0;
  return text[key]?.[index] ?? text[key]?.[0] ?? key;
}
